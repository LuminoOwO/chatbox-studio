"""Writes src/amd_ids.py: Radeon PCI device ids -> (name, gfx target), from pci.ids.

    python3 tools/gen_amd_ids.py /usr/share/misc/pci.ids

The gfx target decides whether AMD's ROCm build can run on a card (Windows can't fake it
like Linux's HSA_OVERRIDE_GFX_VERSION). Chips newer than the pci.ids file are in EXTRA.
"""

import re
import sys
from pathlib import Path

CODENAMES = [  # (regex on the pci.ids name, gfx target) - first match wins
    (r"Navi 10\b|Navi10", "gfx1010"), (r"Navi 12\b|Navi12", "gfx1011"),
    (r"Navi 14\b", "gfx1012"), (r"Navi 21\b", "gfx1030"), (r"Navi 22\b", "gfx1031"),
    (r"Navi 23\b", "gfx1032"), (r"Navi 24\b", "gfx1034"), (r"Navi 31\b", "gfx1100"),
    (r"Navi 32\b", "gfx1101"), (r"Navi 33\b", "gfx1102"), (r"Navi 44\b", "gfx1200"),
    (r"Navi 48\b", "gfx1201"), (r"Vega 10\b", "gfx900"), (r"Vega 12\b", "gfx904"),
    (r"Vega 20\b", "gfx906"), (r"Polaris 2[02]|Ellesmere|Baffin|Lexa|Polaris1[012]", "gfx803"),
    (r"Fiji", "gfx803"), (r"Tonga", "gfx802"), (r"Raven|Picasso", "gfx902"),
    (r"Renoir|Cezanne|Lucienne|Barcelo", "gfx90c"), (r"Rembrandt", "gfx1035"),
    (r"Raphael|Granite Ridge", "gfx1036"), (r"Mendocino", "gfx1037"),
    (r"Phoenix|Hawk Point", "gfx1103"), (r"Van Gogh|Sephiroth", "gfx1033"),
    (r"Strix Halo", "gfx1151"), (r"Strix", "gfx1150"), (r"Krackan", "gfx1152"),
]
SKIP = re.compile(r"USB|Audio|Upstream|Downstream|Coprocessor|SRIOV|MxGPU|PCI Express", re.I)
EXTRA = {  # newer than pci.ids (2025-03)
    "7550": ("AMD Radeon RX 9070 / 9070 XT", "gfx1201"),
    "7551": ("AMD Radeon AI PRO R9700", "gfx1201"),
    "7590": ("AMD Radeon RX 9060 XT", "gfx1200"),
    "150e": ("AMD Radeon 880M / 890M", "gfx1150"),
    "1586": ("AMD Radeon 8050S / 8060S", "gfx1151"),
    "1114": ("AMD Radeon 860M", "gfx1152"),
}


def main(path):
    ids = {}
    inside = False
    for line in Path(path).read_text(encoding="utf-8", errors="replace").splitlines():
        if line.startswith("1002 "):
            inside = True
            continue
        if inside and re.match(r"^[0-9a-f]{4} ", line):
            break
        m = re.match(r"^\t([0-9a-f]{4})  (.+)$", line) if inside else None
        if not m or SKIP.search(m.group(2)):
            continue
        name = m.group(2)
        arch = next((a for rx, a in CODENAMES if re.search(rx, name)), "")
        if arch:
            nice = re.search(r"\[(.+)\]", name)
            ids[m.group(1)] = (("AMD " + nice.group(1)) if nice else name, arch)
    ids.update(EXTRA)
    out = ['"""Radeon PCI device id -> (name, gfx target). Generated by tools/gen_amd_ids.py',
           'from pci.ids - don\'t edit by hand."""', "", "AMD_IDS = {"]
    for k in sorted(ids):
        out.append(f"    {k!r}: {ids[k]!r},")
    out.append("}")
    dest = Path(__file__).resolve().parent.parent / "src" / "amd_ids.py"
    dest.write_text("\n".join(out) + "\n")
    print(f"{len(ids)} ids -> {dest}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "/usr/share/misc/pci.ids")
